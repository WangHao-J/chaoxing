"""A focused review workspace with persistent compatibility and action feedback."""
import tkinter as tk
from tkinter import ttk
from ui_feedback import NoticeVar, Notice
from ui_widgets import wrap_to_width, WorkspaceViewport


def build_review_view(self, account, course):
    window, palette = self.window, self.palette
    embedded = getattr(window, "embedded", False)
    window.title("测验工作台 · " + account)
    window.geometry("1200x940")
    window.minsize(1060, 840)
    window.columnconfigure(1, weight=1)
    window.rowconfigure(0, weight=1)
    rail = ttk.Frame(window, style="Sidebar.TFrame", padding=12 if embedded else 16, width=160 if embedded else 208)
    rail.grid(row=0, column=0, rowspan=2 if embedded else 1, sticky="ns")
    rail.pack_propagate(False)
    ttk.Label(rail, text="章节测验", style="SidebarTitle.TLabel").pack(anchor="w")
    context = ttk.Label(rail, text=f"{account}\n{course}", style="SidebarMuted.TLabel", wraplength=132 if embedded else 174, justify="left")
    context.pack(fill="x", pady=(10, 20))
    self.completion = tk.StringVar()
    ttk.Label(rail, textvariable=self.completion, style="Sidebar.TLabel").pack(anchor="w", pady=(0, 12))
    self.listing = tk.Listbox(rail, width=18, exportselection=False, borderwidth=0,
        highlightthickness=2, highlightbackground=palette["sidebar_muted"], highlightcolor=palette["focus"],
        background=palette["surface"], foreground=palette["text"], selectbackground=palette["selection"],
        selectforeground=palette["on_selection"], activestyle="dotbox")
    self.listing.pack(fill="both", expand=True)
    self.listing.bind("<<ListboxSelect>>", self.select)
    ttk.Label(rail, text="Alt + 左 / 右：切题\n答案可在提交前修改", style="SidebarMuted.TLabel").pack(anchor="w", pady=(16, 0))

    viewport = WorkspaceViewport(window, base_height=780 if embedded else 840, padding=12 if embedded else 24)
    viewport.grid(row=0, column=1, sticky="nsew")
    page = viewport.content
    footer_area = ttk.Frame(window, style="Page.TFrame", padding=(12, 0, 12, 8)) if embedded else page
    if embedded:
        footer_area.grid(row=1, column=1, sticky="ew")
        footer_area.columnconfigure(0, weight=1)
    page.columnconfigure(0, weight=1)
    page.rowconfigure(3, weight=1)
    header = ttk.Frame(page, style="Page.TFrame")
    header.grid(row=0, column=0, sticky="ew", pady=(0, 14))
    ttk.Label(header, text="作答与审核", style="Heading.TLabel").pack(side="left")
    self.question_position = tk.StringVar()
    ttk.Label(header, textvariable=self.question_position, style="Muted.TLabel").pack(side="left", padx=16)
    self.next_button = ttk.Button(header, text="下一题", style="Small.TButton", command=lambda: self.navigate(1))
    self.next_button.pack(side="right")
    self.previous_button = ttk.Button(header, text="上一题", style="Small.TButton", command=lambda: self.navigate(-1))
    self.previous_button.pack(side="right", padx=(0, 8))
    compatibility_row = ttk.Frame(page, style="Page.TFrame")
    compatibility_row.grid(row=1, column=0, sticky="ew", pady=(0, 12))
    self.compatibility = NoticeVar(value="填写所有答案并核对后，即可提交本测验。")
    self.compatibility_notice = Notice(compatibility_row, self.compatibility, compact=True)
    self.compatibility_notice.pack(side="left", fill="both", expand=True)
    self.locate_blocked_button = ttk.Button(compatibility_row, text="定位受阻题", command=self.locate_blocked)
    self.locate_blocked_button.pack(side="right", padx=(8, 0), fill="y")
    tools = ttk.Frame(page, style="Page.TFrame")
    tools.grid(row=2, column=0, sticky="ew", pady=(0, 12))
    self.generate_all_button = ttk.Button(tools, text="AI 补齐未填答案", command=self.suggest_all)
    self.generate_all_button.pack(side="left")
    self.auto_button = ttk.Button(tools, text="后续测验自动填写并提交" if embedded else "自动填写并提交，直到窗口关闭", command=self.automatic)
    self.auto_button.pack(side="left", padx=8)

    body = ttk.Frame(page, style="Panel.TFrame", padding=16)
    body.grid(row=3, column=0, sticky="nsew")
    body.columnconfigure(0, weight=1)
    body.rowconfigure(3, weight=1)
    ttk.Label(body, text="当前题目", style="Subheading.TLabel").grid(row=0, column=0, sticky="w", pady=(0, 8))
    title_frame = ttk.Frame(body, style="Card.TFrame")
    title_frame.grid(row=1, column=0, sticky="ew")
    self.title = tk.Text(title_frame, height=4, wrap="word", font=("Microsoft YaHei UI", 12),
        background=palette["surface"], foreground=palette["text"], borderwidth=0,
        highlightthickness=1, padx=8, pady=8)
    title_scroll = ttk.Scrollbar(title_frame, command=self.title.yview)
    title_scroll.pack(side="right", fill="y")
    self.title.configure(yscrollcommand=title_scroll.set)
    self.title.pack(fill="both", expand=True)
    self.question_issue = tk.StringVar()
    issue_label = ttk.Label(body, textvariable=self.question_issue, style="ErrorText.TLabel")
    issue_label.grid(row=2, column=0, sticky="ew", pady=(5, 6))
    wrap_to_width(issue_label, body, 36)
    self.answer_tabs = ttk.Notebook(body)
    self.answer_tabs.grid(row=3, column=0, sticky="nsew")
    answer_page = ttk.Frame(self.answer_tabs, style="Card.TFrame", padding=8)
    self.explanation_panel = ttk.Frame(self.answer_tabs, style="Card.TFrame", padding=8)
    self.answer_tabs.add(answer_page, text="填写答案")
    self.answer_tabs.add(self.explanation_panel, text="AI 说明与填写方法")
    contextual = ttk.Frame(answer_page, style="Card.TFrame")
    contextual.pack(fill="x", pady=(0, 6))
    self.generate_button = ttk.Button(contextual, text="重新生成本题", command=self.suggest, style="Small.TButton")
    self.generate_button.pack(side="left")
    self.copy_button = ttk.Button(contextual, text="复制已有答案", command=self.copy_answers, style="Small.TButton")
    self.copy_button.pack(side="left", padx=8)
    self.explanation = tk.Text(self.explanation_panel, height=4, wrap="word", font=("Microsoft YaHei UI", 11),
        background=palette["surface"], foreground=palette["text"], borderwidth=0, highlightthickness=1)
    explanation_scroll = ttk.Scrollbar(self.explanation_panel, command=self.explanation.yview)
    explanation_scroll.pack(side="right", fill="y")
    self.explanation.configure(yscrollcommand=explanation_scroll.set)
    self.explanation.pack(fill="both", expand=True)
    self.canvas = tk.Canvas(answer_page, height=100, highlightthickness=0, background=palette["surface"])
    scrollbar = ttk.Scrollbar(answer_page, command=self.canvas.yview)
    scrollbar.pack(side="right", fill="y")
    self.canvas.pack(fill="both", expand=True)
    self.canvas.configure(yscrollcommand=scrollbar.set)
    self.editor = ttk.Frame(self.canvas, style="Card.TFrame")
    self.editor_id = self.canvas.create_window((0, 0), window=self.editor, anchor="nw")
    self.editor.bind("<Configure>", lambda event: self.canvas.configure(scrollregion=self.canvas.bbox("all")))
    self.canvas.bind("<Configure>", lambda event: self.canvas.itemconfigure(self.editor_id, width=event.width))

    feedback_row = ttk.Frame(footer_area, style="Page.TFrame")
    feedback_row.grid(row=0 if embedded else 4, column=0, sticky="ew", pady=(12, 10))
    self.feedback = NoticeVar(value="已恢复草稿，可继续核对。" if self.answers else "可使用 AI 一次补齐答案，也可直接填写。")
    self.feedback_notice = Notice(feedback_row, self.feedback, compact=True)
    self.feedback_notice.pack(side="left", fill="both", expand=True)
    status = ttk.Frame(feedback_row, style="Page.TFrame")
    status.pack(side="right", padx=(8, 0))
    self.wait_status = tk.StringVar()
    ttk.Label(status, textvariable=self.wait_status, style="Muted.TLabel").pack(anchor="e")
    self.cancel_button = ttk.Button(status, text="取消生成", command=self.cancel_ai, style="Small.TButton", state="disabled")
    self.cancel_button.pack(anchor="e", pady=(4, 0))
    bottom = ttk.Frame(footer_area, style="Page.TFrame")
    bottom.grid(row=1 if embedded else 5, column=0, sticky="ew")
    self.review_checkbox = ttk.Checkbutton(bottom, text="我已逐题核对，确认提交本次答案", variable=self.reviewed, command=self.update_submit)
    self.review_checkbox.pack(anchor="w", pady=(0, 8))
    actions = ttk.Frame(bottom, style="Page.TFrame")
    actions.pack(fill="x")
    self.defer_button = ttk.Button(actions, text="跳过本次答题", command=self.skip)
    self.skip_button = self.defer_button
    self.defer_button.pack(side="left")
    self.skip_all_button = ttk.Button(actions, text="跳过后续所有答题", command=lambda: self.skip(True))
    self.skip_all_button.pack(side="left", padx=8)
    self.submit_button = ttk.Button(actions, text="确认提交本测验", command=self.confirm_submit, style="Primary.TButton", state="disabled")
    self.submit_button.pack(side="right")
    ttk.Label(bottom, text="自动答题仅作用于当前账号；重新打开此账号后需再次启用。" if embedded else "当前账户自动答题持续到窗口关闭；个别失败保留待处理。全部跳过仅本轮生效。", style="Muted.TLabel").pack(anchor="w", pady=(8, 0))
    for widget in (self.title, self.explanation):
        widget.bind("<Tab>", lambda event: focus_relative(event.widget, 1))
        widget.bind("<Shift-Tab>", lambda event: focus_relative(event.widget, -1))
    window.bind("<Alt-Left>", lambda event: self.navigate(-1))
    window.bind("<Alt-Right>", lambda event: self.navigate(1))
    window.bind("<Control-Return>", lambda event: self.confirm_submit())
    window.bind("<Escape>", lambda event: self.defer())


def focus_relative(widget, direction):
    (widget.tk_focusNext() if direction > 0 else widget.tk_focusPrev()).focus_set()
    return "break"
